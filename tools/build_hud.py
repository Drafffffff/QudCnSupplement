#!/usr/bin/env python3
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
pairs=json.loads((ROOT/'data/hud-ui.json').read_text());bykey={}
for k,v in pairs.items():
 if k.lower() in bykey:assert bykey[k.lower()][1]==v
 bykey[k.lower()]=(k,v)
q=lambda x:json.dumps(x,ensure_ascii=False)
s=['// Generated by tools/build_hud.py; complete UI labels only.','using System; using System.Collections.Generic;','public static class QudCnHudData {','public static readonly Dictionary<string,string> Labels = new Dictionary<string,string>(StringComparer.OrdinalIgnoreCase) {']
for k,v in sorted(bykey.values()):s.append('{'+q(k)+','+q(v)+'},')
s+=['};','}'];(ROOT/'mod/QudCnHudData.cs').write_text('\n'.join(s)+'\n')
print('HUD labels',len(bykey))
