#!/usr/bin/env python3
"""Extract audited exact UI mappings and anchored message patterns from TW upstream.
Only Chinese segments are converted; English regex keys and game tokens stay intact.
Global word replacement and VariableReplacer overrides are deliberately excluded.
"""
from pathlib import Path
import re, json
from opencc import OpenCC
ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'sources/333640/3777949908'
cc = OpenCC('t2s')
def chinese_only(s):
    return re.sub(r'[\u3400-\u9fff]+', lambda m: cc.convert(m[0]), s)
def dictionary(name, text):
    start = re.search(r'\b'+name+r'\s*=\s*\n?\s*new Dictionary<string, string>[^\{]*\{', text)
    if not start: return []
    block = text[start.end():text.index('\n        };', start.end())]
    return re.findall(r'\{\s*"((?:\\.|[^"\\])*)"\s*,\s*"((?:\\.|[^"\\])*)"\s*\}', block)
ui = (UPSTREAM/'UiStringsHook.cs').read_text()
cleaner = (UPSTREAM/'TextCleanerHook.cs').read_text()
# Exact complete UI strings only. Single-word dictionaries are intentionally omitted:
# a user's character could be named "Hope", "Walk", "Will", etc.
phrases = dict(dictionary('UiPhrases', ui) + dictionary('SectionHeaders', ui) + dictionary('JournalCategories', ui))
phrases.update({'No Equipment Set':'无装备套装','No active effects.':'无生效中的效果。','Active Effects':'生效中的效果','Save and Quit':'保存并退出'})
# SentenceDict is a complete-string lookup, safe to add on display paths.
phrases.update(dictionary('SentenceDict', cleaner))
lines = ['// Generated by tools/build_dynamic.py. See THIRD_PARTY_NOTICES.md.',
'using System;', 'using System.Collections.Generic;', 'using System.Text.RegularExpressions;',
'public static class QudCnSupplementData {',
'public static readonly Dictionary<string,string> Ui = new Dictionary<string,string>(StringComparer.Ordinal) {']
for k,v in sorted(phrases.items()):
    lines.append('  {"'+k+'", "'+chinese_only(v)+'"},')
lines.extend(['};','public static readonly Tuple<Regex,string>[] Patterns = new Tuple<Regex,string>[] {'])
# Known mixed-language screenshot structures must run before more general patterns.
extra = [
(r'^你\s+take\s+(?:the |a |an )?(.+?)[。.]$', '你拿取了$1。'),
(r'^你\s+miss\s+使用\s+(.+?)\s+未命中[！!。.]?$', '你用$1攻击，但未命中！'),
# Already-localized physics messages still receive English object articles at runtime.
(r'^你经过了\s+(?:the |a |an )?(.+?)[。.]$', '你经过了$1。'),
(r'^道路被\s+(?:the |a |an )?(.+?)\s+挡住了[。.]$', '道路被$1挡住了。'),
(r'^(?:The )?(.+?) misses 使用 (?:his |her |its |their )?(.+?) 未命中你[.!]?(?: ?(\[[^\]]*\]))?$', '$1用$2攻击你，但未命中！$3'),
(r'^你将 (?:the |a |an )?(.+?) 识别为 (?:the |a |an )?(.+?)[.!。]?$', '你将$1识别为$2。'),
(r'^(?:You|你) identify (?:the |a |an )?(.+?) as (?:the |a |an )?(.+?)[.!]?$', '你将$1识别为$2。'),
(r'^你 equip (?:the |a |an )?(.+?)[.!]?$', '你装备了$1。'),
(r'^你 unequip (?:the |a |an )?(.+?)[.!]?$', '你卸下了$1。'),
]
for pattern,value in extra:
    lines.append('Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "'+value+'"),')
harmony = (UPSTREAM/'HarmonyPatches.cs').read_text()
block = harmony[harmony.index('private static readonly List<Tuple<Regex, string>> Patterns'):harmony.index('private static readonly Regex Possessive')]
seen=set()
for line in block.splitlines():
    if 'Tuple.Create(new Regex' in line:
        line = chinese_only(line.strip())
        if line not in seen:
            lines.append(line); seen.add(line)
# Import whole, anchored sentence patterns from the cleaner, excluding substring/word cleanup.
for pattern,value in re.findall(r'Regex.Replace\(\s*text, @"((?:""|[^"])*)",\s*"((?:\\.|[^"\\])*)",\s*System.Text.RegularExpressions.RegexOptions.IgnoreCase\)', cleaner):
    if not (pattern.startswith('^') and pattern.endswith('$')): continue
    # Toggle is added below with fixed on/off branches, avoiding an untranslated capture.
    if 'toggle' in pattern or 'emit' in pattern: continue
    line='Tuple.Create(new Regex(@"'+chinese_only(pattern)+'", RegexOptions.IgnoreCase), "'+chinese_only(value)+'"),'
    if line not in seen: lines.append(line); seen.add(line)
# Narrow typed slots: leave subjects, proper names and item labels untouched.
sources={'freezing':'冰冻','cold':'寒冷','heat':'高温','burning':'燃烧','fire':'火焰','bleeding':'流血','poison':'中毒','acid':'酸液','electricity':'电击','falling':'坠落','thirst':'口渴','starvation':'饥饿','suffocation':'窒息'}
for source,zh in sources.items():
    pattern=r'^(?:You|你)\s+(?:take|受到)\s+(\d+)\s+damage\s+from\s+'+r'(?:the )?'+source+r'[.!]?(?: ?(\[[^\]]*\]))?$'
    # Insert ahead of generic damage-from pattern, so the typed source is translated.
    line='Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "你因'+zh+'受到$1伤害$2。"),'
    lines.insert(lines.index('public static readonly Tuple<Regex,string>[] Patterns = new Tuple<Regex,string>[] {')+1,line); seen.add(line)
    pattern=r'^(?:The )?(.+?)\s+(?:takes?|受到)\s+(\d+)\s+damage\s+from\s+(?:the )?'+source+r'[.!]?(?: ?(\[[^\]]*\]))?$'
    line='Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "$1因'+zh+'受到$2伤害$3。"),'
    lines.insert(lines.index('public static readonly Tuple<Regex,string>[] Patterns = new Tuple<Regex,string>[] {')+2,line); seen.add(line)
for state,zh in [('on','开启'),('off','关闭')]:
    pattern=r'^(?:You|你)\s+toggle\s+(.+?)\s+'+state+r'[.!]?$'
    lines.append('Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "你将$1'+zh+'。"),'); seen.add(pattern)
# Structured ability grammar with an explicit ray and anatomical slot.
for ray,zh in [('flaming','火焰'),('freezing','冰冻')]:
    pattern=r'^(?:You|你)\s+emit(?:ted)?\s+(?:a|an)\s+'+ray+r' ray\s+from\s+(?:your|你的)\s+(?:hands|hand|手|双手)[.!]?$'
    lines.append('Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "你从双手射出一道'+zh+'射线。"),'); seen.add(pattern)
    pattern=r'^(?:The )?(.+?)\s+emit(?:s|ted)?\s+(?:a|an)\s+'+ray+r' ray\s+from\s+(?:its|his|her|它的|他的|她的)\s+(?:hands|hand|手|双手)[.!]?$'
    lines.append('Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "$1从双手射出一道'+zh+'射线。"),'); seen.add(pattern)
# Common fixed action frames from upstream phrase dictionary. These are full sentences,
# never global substring replacements (a generated name containing 'flames' is preserved).
actions=dictionary('PhraseLeaks',cleaner)
allowed=('emit a ', 'project a ', 'invoke a ', 'feel a ', 'resist ', 'roll on ', 'beat at ', 'shimmer into ', 'shoot a ', 'spew a ', 'gain the ', 'gain all ', 'stand up', 'sit down', 'lie down')
for action,zh in actions:
    if not action.startswith(allowed): continue
    # Skip templates and malformed fragments.
    if any(c in action for c in '=|{}'): continue
    pattern=r'^(?:You|你)\s+'+re.escape(action)+r'[.!]?$'
    lines.append('Tuple.Create(new Regex(@"'+pattern+'", RegexOptions.IgnoreCase), "你'+chinese_only(zh)+'。"),'); seen.add(pattern)
lines.extend(['};','public static readonly Dictionary<string,string> Effects = new Dictionary<string,string>(StringComparer.OrdinalIgnoreCase) {'])
for k,v in dictionary('EffectZh', cleaner):
    lines.append('  {"'+k+'", "'+chinese_only(v)+'"},')
lines.extend(['};','}'])
(ROOT/'mod/QudCnSupplementData.cs').write_text('\n'.join(lines)+'\n')
print(json.dumps({'exact_ui_strings':len(phrases),'message_patterns':len(seen)+len(extra)},ensure_ascii=False))
